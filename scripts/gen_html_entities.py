#!/usr/bin/env python3
"""Generate src/html_entities.h: the HTML5 named character references of
html.entities.html5, which html.unescape (and so markupsafe's striptags) uses.

The table follows the html5 dictionary of the Python that runs this script. Names keep their
trailing ';' where they have one (some legacy names, like 'amp', exist with and without).
Regenerate with
    python3 scripts/gen_html_entities.py && clang-format -i src/html_entities.h
"""
import html.entities
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

HELPER = """// The entity called name (with its ';' if it has one), or nullptr
inline const HtmlEntity* FindHtmlEntity(std::string_view name)
{
    auto it = std::lower_bound(std::begin(HtmlEntities), std::end(HtmlEntities), name, [](const HtmlEntity& entity, std::string_view value) { return std::string_view(entity.name) < value; });
    return it != std::end(HtmlEntities) && std::string_view(it->name) == name ? &*it : nullptr;
}
"""


def main():
    rows = []
    for name in sorted(html.entities.html5):
        cps = [ord(ch) for ch in html.entities.html5[name]]
        assert 1 <= len(cps) <= 2 and name.isascii()
        rows.append('    {{ "{}", 0x{:X}, 0x{:X} }},'.format(name, cps[0], cps[1] if len(cps) > 1 else 0))
    parts = [
        "// Generated by scripts/gen_html_entities.py from Python {}.{}'s html.entities.html5; do not edit.\n".format(*sys.version_info[:2]),
        "#ifndef JINJA2CPP_SRC_HTML_ENTITIES_H\n#define JINJA2CPP_SRC_HTML_ENTITIES_H\n",
        "#include <algorithm>\n#include <cstdint>\n#include <iterator>\n#include <string_view>\n",
        "namespace jinja2\n{\nnamespace html\n{\n",
        "// A named character reference and the one or two code points it stands for (0 when only one)\n"
        "struct HtmlEntity\n{\n    const char* name;\n    uint32_t first;\n    uint32_t second;\n};\n",
        "// Sorted by name\nconstexpr HtmlEntity HtmlEntities[] = {\n" + "\n".join(rows) + "\n};\n",
        HELPER,
        "} // namespace html\n} // namespace jinja2\n\n#endif // JINJA2CPP_SRC_HTML_ENTITIES_H\n",
    ]
    (ROOT / "src" / "html_entities.h").write_text("\n".join(parts), encoding="utf-8")


if __name__ == "__main__":
    main()
