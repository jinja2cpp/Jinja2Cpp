#!/usr/bin/env python3
"""Generate test/json_test_suite_cases.inc from a JSONTestSuite checkout.

Usage: scripts/json_test_suite.py PATH/TO/JSONTestSuite

JSONTestSuite (https://github.com/nst/JSONTestSuite, MIT, Nicolas Seriot) lists RFC 8259
parsing cases: y_ must be accepted, n_ rejected, i_ is implementation-defined. Each file
becomes one row with its bytes; files over 4 KiB (two deep-nesting cases) are left out and
test/json_reader_test.cpp builds their equivalents itself. The pinned revision is in
sbom/components.json; check it out before regenerating.
"""
import pathlib
import subprocess
import sys

MAX_SIZE = 4096


def c_string(data):
    out = []
    for b in data:
        if b in (0x22, 0x5C):
            out.append('\\' + chr(b))
        elif 0x20 <= b < 0x7F and b != 0x3F:  # '?' avoids trigraph-like sequences
            out.append(chr(b))
        else:
            out.append('\\x%02x""' % b)
    return '"' + ''.join(out) + '"'


def main():
    root = pathlib.Path(sys.argv[1])
    revision = subprocess.run(['git', '-C', str(root), 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    rows = []
    for path in sorted((root / 'test_parsing').glob('*.json')):
        data = path.read_bytes()
        if len(data) > MAX_SIZE:
            continue
        rows.append('{ "%s", %s, %d },' % (path.stem, c_string(data), len(data)))
    out = pathlib.Path(__file__).resolve().parent.parent / 'test' / 'json_test_suite_cases.inc'
    out.write_text(
        '// Generated by scripts/json_test_suite.py from JSONTestSuite ' + revision + '\n'
        '// (https://github.com/nst/JSONTestSuite, MIT License, Copyright (c) 2016 Nicolas Seriot).\n'
        '// Do not edit. Rows: { file name, bytes, size }.\n'
        '// clang-format off\n' + '\n'.join(rows) + '\n// clang-format on\n')


if __name__ == '__main__':
    main()
